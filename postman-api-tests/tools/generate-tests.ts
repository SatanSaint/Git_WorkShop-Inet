/**
 * generate-tests.ts
 *
 * แปลง Postman Collection JSON → ไฟล์ Vitest (TypeScript) พร้อมรันทดสอบ API
 *
 * วิธีรัน:
 *   npm run generate
 *   หรือ: npx tsx tools/generate-tests.ts [path/to/collection.json] [output/spec.ts]
 *
 * ค่า default:
 *   input  = postman/collection.json
 *   output = tests/generated.api.spec.ts
 */

import fs from "node:fs";
import path from "node:path";

// ---------------------------------------------------------------------------
// Types (ใช้ any เพราะ Postman schema ซับซ้อนและหลายเวอร์ชัน)
// ---------------------------------------------------------------------------
type AnyObj = Record<string, unknown>;

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
function asStringUrl(urlObj: unknown): string {
  if (!urlObj) return "";
  if (typeof urlObj === "string") return urlObj;
  const u = urlObj as AnyObj;
  if (typeof u["raw"] === "string") return u["raw"];
  const protocol = u["protocol"] ? `${u["protocol"]}://` : "";
  const host = Array.isArray(u["host"])
    ? (u["host"] as string[]).join(".")
    : String(u["host"] ?? "");
  const parts = Array.isArray(u["path"])
    ? (u["path"] as string[]).join("/")
    : String(u["path"] ?? "");
  const queryArr = Array.isArray(u["query"])
    ? (u["query"] as AnyObj[])
    : [];
  const query =
    queryArr.length
      ? "?" +
        queryArr
          .filter((q) => !q["disabled"])
          .map((q) => `${q["key"]}=${q["value"] ?? ""}`)
          .join("&")
      : "";
  return `${protocol}${host}/${parts}${query}`.replace(/([^:])\/\/+/g, "$1/");
}

interface FlatItem {
  __name: string;
  request: AnyObj | null;
}

function flattenItems(items: AnyObj[], out: FlatItem[] = [], prefix = ""): FlatItem[] {
  for (const it of items ?? []) {
    const name = String(it["name"] ?? "");
    const fullName = prefix ? `${prefix} / ${name}` : name;
    if (Array.isArray(it["item"])) {
      flattenItems(it["item"] as AnyObj[], out, fullName);
    } else {
      out.push({ __name: fullName, request: (it["request"] as AnyObj) ?? null });
    }
  }
  return out;
}

function indent(n: number): string {
  return "  ".repeat(n);
}

function safeJson(v: unknown, spaces = 0): string {
  return JSON.stringify(v, null, spaces || undefined);
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
const collectionPath = process.argv[2] ?? "postman/collection.json";
const outFile = process.argv[3] ?? "tests/generated.api.spec.ts";

if (!fs.existsSync(collectionPath)) {
  console.error(`❌  ไม่พบไฟล์: ${collectionPath}`);
  console.error(`   วางไฟล์ Postman collection ไว้ที่ postman/collection.json`);
  console.error(`   หรือรัน: npm run fetch  เพื่อดึงจาก Postman API`);
  process.exit(1);
}

const raw = JSON.parse(fs.readFileSync(collectionPath, "utf8")) as AnyObj;
// รองรับทั้งรูปแบบ export โดยตรง และรูปแบบที่ดึงจาก API
const col = (raw["collection"] as AnyObj) ?? raw;
const colName = (col["info"] as AnyObj | undefined)?.["name"] ?? "Postman Collection";
const items = flattenItems((col["item"] as AnyObj[]) ?? []);

const lines: string[] = [];

lines.push(`/**`);
lines.push(` * ${outFile}`);
lines.push(` * Auto-generated by tools/generate-tests.ts`);
lines.push(` * Collection: ${colName}`);
lines.push(` * Generated: ${new Date().toISOString()}`);
lines.push(` *`);
lines.push(` * ⚠️  ตรวจสอบและปรับ assertions ก่อน commit`);
lines.push(` */`);
lines.push(``);
lines.push(`import { describe, it, expect } from "vitest";`);
lines.push(`import axios from "axios";`);
lines.push(``);
lines.push(`// ---------------------------------------------------------------------------`);
lines.push(`// Config from environment variables`);
lines.push(`// ---------------------------------------------------------------------------`);
lines.push(`const BASE_URL = (process.env["BASE_URL"] ?? "").replace(/\\/$/, "");`);
lines.push(`const TOKEN = process.env["TOKEN"];`);
lines.push(``);
lines.push(`/**`);
lines.push(` * Resolve URL:`);
lines.push(` *  - full URL (https://...) → ใช้ตามเดิม`);
lines.push(` *  - relative path          → ต่อกับ BASE_URL`);
lines.push(` *  - {{baseUrl}}/path       → แทนด้วย BASE_URL`);
lines.push(` */`);
lines.push(`function resolveUrl(raw: string): string {`);
lines.push(`  const replaced = raw`);
lines.push(`    .replace(/\\{\\{baseUrl\\}\\}/gi, BASE_URL)`);
lines.push(`    .replace(/\\{\\{base_url\\}\\}/gi, BASE_URL);`);
lines.push(`  if (/^https?:\\/\\//i.test(replaced)) return replaced;`);
lines.push(`  if (!BASE_URL) throw new Error("BASE_URL is required for relative URLs");`);
lines.push(`  return BASE_URL + "/" + replaced.replace(/^\\//, "");`);
lines.push(`}`);
lines.push(``);
lines.push(`// ---------------------------------------------------------------------------`);
lines.push(`// Tests`);
lines.push(`// ---------------------------------------------------------------------------`);
lines.push(`describe(${safeJson(String(colName))}, () => {`);

let testCount = 0;

for (const item of items) {
  const req = item.request;
  if (!req) continue;

  const name = item.__name.replace(/`/g, "'");
  const method = String(req["method"] ?? "GET").toUpperCase();
  const rawUrl = asStringUrl(req["url"]);

  // headers
  const headerArr = Array.isArray(req["header"]) ? (req["header"] as AnyObj[]) : [];
  const headers: Record<string, string> = {};
  for (const h of headerArr) {
    if (h["disabled"]) continue;
    if (typeof h["key"] === "string") {
      headers[h["key"]] = String(h["value"] ?? "");
    }
  }

  // body
  const body = req["body"] as AnyObj | undefined;
  let bodyLines: string[] = [];
  if (body?.["mode"] === "raw" && typeof body["raw"] === "string" && (body["raw"] as string).trim()) {
    bodyLines = [`${indent(3)}data: ${safeJson(body["raw"])},`];
  } else if (body?.["mode"] === "urlencoded" && Array.isArray(body["urlencoded"])) {
    const params: Record<string, string> = {};
    for (const p of body["urlencoded"] as AnyObj[]) {
      if (!p["disabled"] && typeof p["key"] === "string") {
        params[p["key"]] = String(p["value"] ?? "");
      }
    }
    bodyLines = [`${indent(3)}data: ${safeJson(params, 8)},`];
  } else if (body?.["mode"] === "formdata" && Array.isArray(body["formdata"])) {
    const params: Record<string, string> = {};
    for (const p of body["formdata"] as AnyObj[]) {
      if (!p["disabled"] && typeof p["key"] === "string" && p["type"] !== "file") {
        params[p["key"]] = String(p["value"] ?? "");
      }
    }
    bodyLines = [`${indent(3)}data: ${safeJson(params, 8)}, // formdata (files excluded)`];
  }

  lines.push(``);
  lines.push(`${indent(1)}it(\`${name}\`, async () => {`);
  lines.push(`${indent(2)}const url = resolveUrl(${safeJson(rawUrl)});`);
  lines.push(`${indent(2)}const res = await axios.request({`);
  lines.push(`${indent(3)}method: ${safeJson(method)},`);
  lines.push(`${indent(3)}url,`);
  lines.push(`${indent(3)}headers: {`);
  if (Object.keys(headers).length > 0) {
    for (const [k, v] of Object.entries(headers)) {
      lines.push(`${indent(4)}${safeJson(k)}: ${safeJson(v)},`);
    }
  }
  lines.push(`${indent(4)}...(TOKEN ? { Authorization: \`Bearer \${TOKEN}\` } : {}),`);
  lines.push(`${indent(3)}},`);
  if (bodyLines.length > 0) lines.push(...bodyLines);
  lines.push(`${indent(3)}validateStatus: () => true,`);
  lines.push(`${indent(2)}});`);
  lines.push(``);
  lines.push(`${indent(2)}// TODO: ปรับ assertion ตามที่ต้องการ`);
  lines.push(`${indent(2)}expect(res.status, \`[${method}] ${rawUrl} should not be a server error\`).toBeLessThan(500);`);
  lines.push(`${indent(1)}});`);

  testCount++;
}

lines.push(`});`);
lines.push(``);

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join("\n"), "utf8");

console.log(`✅  Generated ${testCount} test(s) → ${outFile}`);
console.log(`   รันเทส: BASE_URL="https://your-api.com" TOKEN="..." npm test`);
